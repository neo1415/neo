// Builds prototype/src/styles/tokens.css from tokens.json and fails if any declared text pair misses its contrast ratio.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'));

const ref = (path) => path.split('.').reduce((o, k) => o?.[k], t.ref);
const cssName = (k) => '--' + k.replace(/\./g, '-');

function lum(hex) {
  const n = hex.replace('#', '');
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(n.slice(i, i + 2), 16) / 255)
    .map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };

const failures = [];
const report = [];
for (const [theme, map] of Object.entries(t.themes)) {
  const val = (k) => ref(map[k]);
  for (const [fg, bg, min] of t.contrast) {
    const r = ratio(val(fg), val(bg));
    report.push(`${theme.padEnd(5)} ${fg} on ${bg}: ${r.toFixed(2)} (min ${min})`);
    if (r < min) failures.push(`${theme}: ${fg} ${val(fg)} on ${bg} ${val(bg)} = ${r.toFixed(2)} < ${min}`);
  }
}

const lines = ['/* Generated by talent-q-design/tokens/build.mjs from tokens.json. Do not edit. */', ':root {'];
for (const [group, scale] of Object.entries(t.ref)) for (const [k, v] of Object.entries(scale)) lines.push(`  --ref-${group}-${k}: ${v};`);
for (const g of ['space', 'radius', 'font', 'size', 'motion', 'target']) for (const [k, v] of Object.entries(t[g])) lines.push(`  --${g}-${k}: ${v};`);
lines.push('}');
const themeBlock = (sel, map) => [`${sel} {`, ...Object.entries(map).map(([k, v]) => `  ${cssName(k)}: var(--ref-${v.replace('.', '-')});`), '}'];
lines.push(...themeBlock(':root, [data-theme="dark"]', t.themes.dark));
lines.push('@media (prefers-color-scheme: light) {', ...themeBlock('  :root:not([data-theme="dark"])', t.themes.light).map((l) => '  ' + l), '}');
lines.push(...themeBlock('[data-theme="light"]', t.themes.light));
lines.push('/* Paper surfaces: artifacts sit on paper in either theme (D1). */');
lines.push('.paper {', '  --color-text: var(--color-paper-text);', '  --color-text-muted: var(--color-paper-muted);', '  --color-text-subtle: var(--color-paper-muted);',
  '  --color-line: var(--color-paper-line);', '  --color-surface: var(--color-paper-raised);', '  --color-surface-raised: var(--color-paper-raised);', '  --color-surface-sunken: var(--ref-paper-1);', '  --color-q: var(--ref-gold-600);', '  --color-q-text: var(--color-paper-q-text);',
  '  --color-action: var(--ref-ink-900);', '  --color-on-action: var(--ref-paper-0);', '  --color-focus: var(--ref-gold-700);', '  --color-line-strong: var(--ref-ink-900);',
  '  --color-ok: var(--ref-green-light);', '  --color-warn: var(--ref-amber-light);', '  --color-risk: var(--ref-red-light);', '  --color-info: var(--ref-blue-light);',
  '  background: var(--color-paper);', '  color: var(--color-paper-text);', '}');

const out = join(here, '..', 'prototype', 'src', 'styles');
mkdirSync(out, { recursive: true });
writeFileSync(join(out, 'tokens.css'), lines.join('\n') + '\n');
writeFileSync(join(here, 'CONTRAST-REPORT.txt'), report.join('\n') + '\n');
if (failures.length) { console.error('Contrast failures:\n' + failures.join('\n')); process.exit(1); }
console.log(`tokens.css written; ${report.length} contrast pairs pass`);
