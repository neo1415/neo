// Builds handoff/q-eval-corpus.json and handoff/Q-SKILLS-APPENDIX.md from the prototype:
// every phrase the journey tests type to Q (with the verified outcome that follows it) becomes an
// evaluation case for production Q; every skill and proactive rule is listed by area.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
const root = new URL('..', import.meta.url).pathname;
const J = join(root, 'qa/scripts/journeys');
const cases = [];
for (const f of readdirSync(J).filter((x) => /^[RT]\d\.mjs$/.test(x))) {
  const src = readFileSync(join(J, f), 'utf8').split('\n');
  src.forEach((line, i) => {
    for (const m of line.matchAll(/\bask\((?:page,\s*)?(['"`])((?:(?!\1).)+)\1/g)) {
      const after = src.slice(i, i + 6).join(' ');
      const step = after.match(/step\((?:v,\s*)?['"`]([^'"`]+)['"`]/);
      cases.push({ journey: f.replace('.mjs', ''), said: m[2], verified: step ? step[1] : null, source: `qa/scripts/journeys/${f}:${i + 1}` });
    }
  });
}
writeFileSync(join(root, 'handoff/q-eval-corpus.json'), JSON.stringify(cases, null, 1));
const S = join(root, 'prototype/src/q');
const rows = [];
for (const dir of ['skills', 'proactive']) for (const f of readdirSync(join(S, dir))) {
  const t = readFileSync(join(S, dir, f), 'utf8');
  const ids = [...t.matchAll(/register(?:Skill|Rule)\(\{\s*id:\s*['"]([^'"]+)['"](?:,\s*side:\s*['"]([^'"]+)['"])?/g)].map((m) => ({ id: m[1], side: m[2] ?? '' }));
  const ops = [...t.matchAll(/registerOp\(['"]([^'"]+)['"]/g)].map((m) => m[1]);
  rows.push({ kind: dir === 'skills' ? 'skill' : 'rule', file: `prototype/src/q/${dir}/${f}`, ids, ops });
}
const md = ['# Q skills, proactive rules and operations in the prototype', '', 'Generated by `scripts/extract-q-corpus.mjs`. Each skill is a rule-based stand-in for a production intent plus tools (see Q-INTELLIGENCE-SPEC.md §2). Operations are the state changes Q can perform; in production each becomes a tool or service call with the same permission and approval rules.', ''];
for (const r of rows) md.push(`## ${r.file} · ${r.kind === 'skill' ? 'skills' : 'proactive rules'}: ${r.ids.length}${r.ops.length ? ` · operations: ${r.ops.length}` : ''}`, '', r.ids.map((x) => `\`${x.id}\`${x.side ? ` (${x.side})` : ''}`).join(' · ') || '—', ...(r.ops.length ? ['', `Operations: ${r.ops.map((o) => `\`${o}\``).join(' · ')}`] : []), '');
writeFileSync(join(root, 'handoff/Q-SKILLS-APPENDIX.md'), md.join('\n'));
console.log(`${cases.length} corpus cases · ${rows.reduce((n, r) => n + r.ids.length, 0)} skills/rules · ${rows.reduce((n, r) => n + r.ops.length, 0)} operations`);
