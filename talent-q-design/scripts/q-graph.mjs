// Q dependency graph (vision V40, "graphified code understanding", a developer pilot for Q traceability).
// Graphify itself is not installed, so this reads the prototype's source and builds the same traceability:
// Q skill → ops it runs → state slices it touches, and route → state slices, from registerSkill / registerOp /
// registerRoute calls and imports. Output: handoff/q-graph.json and handoff/Q-DEPENDENCY-GRAPH.md.
// Usage: node talent-q-design/scripts/q-graph.mjs
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'prototype', 'src');
const files = [];
(function walk(d) { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else if (/\.tsx?$/.test(f)) files.push(p); } })(src);

const rel = (p) => relative(src, p);
const text = Object.fromEntries(files.map((f) => [rel(f), readFileSync(f, 'utf8')]));
// Which state slices a file touches: area accessors and direct w.areas['x'] / w.areas.x reads.
const slicesIn = (t) => [...new Set([...t.matchAll(/areas(?:\.|\[')([a-z][\w-]*)/g)].map((m) => m[1]).concat([...t.matchAll(/from '[./]*state\/areas\/([\w-]+)'/g)].map((m) => m[1])))].sort();
const localImports = (file, t) => [...t.matchAll(/from '(\.[^']+)'/g)].map((m) => rel(join(src, dirname(file), m[1]))).map((p) => Object.keys(text).find((k) => k === p + '.ts' || k === p + '.tsx' || k === p + '/index.ts')).filter(Boolean);

const skills = []; const ops = []; const routes = [];
for (const [f, t] of Object.entries(text)) {
  for (const m of t.matchAll(/registerSkill\(\{\s*id:\s*'([^']+)',\s*side:\s*'(\w+)'/g)) skills.push({ id: m[1], side: m[2], file: f });
  for (const m of t.matchAll(/registerOp\('([^']+)'/g)) ops.push({ op: m[1], file: f });
  for (const m of t.matchAll(/registerRoute\(\{\s*path:\s*['`]([^'`]+)['`]([^\n]*)/g)) routes.push({ path: m[1], side: m[2].match(/side:\s*'(\w+)'/)?.[1] ?? '?', file: f });
}
// A file's reach: its own slices plus those of the local modules it imports (one level, which is where the area logic lives).
const reach = (f) => [...new Set([...slicesIn(text[f]), ...localImports(f, text[f]).flatMap((g) => slicesIn(text[g]))])].sort();
const opsUsed = (f) => [...new Set([...text[f].matchAll(/op:\s*'([^']+)'/g)].map((m) => m[1]))].sort();

const graph = {
  generated: new Date().toISOString().slice(0, 10),
  skills: skills.map((s) => ({ ...s, ops: opsUsed(s.file), slices: reach(s.file) })),
  ops: ops.map((o) => ({ ...o, slices: reach(o.file) })),
  routes: routes.map((r) => ({ ...r, slices: reach(r.file) })),
};
writeFileSync(join(root, 'handoff', 'q-graph.json'), JSON.stringify(graph, null, 1));

const bySlice = {};
for (const s of graph.skills) for (const x of s.slices) (bySlice[x] ??= { skills: new Set(), routes: new Set() }).skills.add(s.id);
for (const r of graph.routes) for (const x of r.slices) (bySlice[x] ??= { skills: new Set(), routes: new Set() }).routes.add(r.path);
const md = `# Q dependency graph (V40 pilot)

Generated by \`scripts/q-graph.mjs\` from the prototype source on ${graph.generated}. Do not edit by hand.

It answers the founder's V40 question, "if this changes, what does Q touch?", without Graphify, which is not installed. It records:
- which Q skills and operations exist;
- which state slices each one reads or writes;
- which pages read the same slices.

Full data is in \`handoff/q-graph.json\`. The extraction is regex-based and one import level deep: it shows where to look, and it is not a proof.

| | Count |
|---|---|
| Q skills | ${graph.skills.length} (${graph.skills.filter((s) => s.side === 'recruiter').length} recruiter, ${graph.skills.filter((s) => s.side === 'candidate').length} candidate, ${graph.skills.filter((s) => !['recruiter', 'candidate'].includes(s.side)).length} both) |
| Q operations (actions with undo or approval) | ${graph.ops.length} |
| Routes | ${graph.routes.length} |
| State slices touched | ${Object.keys(bySlice).length} |

## Impact by state slice (what to retest when a slice changes)

| Slice | Q skills | Pages |
|---|---|---|
${Object.entries(bySlice).sort().map(([k, v]) => `| \`${k}\` | ${v.skills.size} | ${[...v.routes].sort().map((p) => `\`${p}\``).join(', ') || '—'} |`).join('\n')}

## How production uses this

The same extraction runs in CI against the real app's tool registry, so that a change to a module lists the Q tools and pages to retest. This is the traceability V40 asks for. Adopting Graphify itself stays a research option, not a dependency.
`;
writeFileSync(join(root, 'handoff', 'Q-DEPENDENCY-GRAPH.md'), md);
console.log(`${graph.skills.length} skills, ${graph.ops.length} ops, ${graph.routes.length} routes, ${Object.keys(bySlice).length} slices`);
